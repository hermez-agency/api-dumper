import type { EnumDefinition, OpenApiDocument } from "../config.js"

type Schema = Record<string, any>
type EnumValue = string | number | boolean

export const GENERATED_MARKER = "Generated by api-dumper"

/**
 * Reads the standard `enum` keyword: every named schema carrying one becomes
 * an enum, and, with `inline`, so does every property declaring one directly.
 *
 * Extensions recognised on the schema:
 * - `x-enum-name`: TypeScript name, instead of the one derived from the key;
 * - `x-enum-varnames` (or `x-enumNames`): key of each value, useful for numeric enums;
 * - `x-enum-iris`: IRI of each value (`{ "MALE": "/api/genders/MALE" }`), for JSON-LD.
 */
export function collectEnums(document: OpenApiDocument, options: { inline?: boolean } = {}): EnumDefinition[] {
  const schemas: Record<string, Schema> = document.components?.schemas ?? {}
  const enums: EnumDefinition[] = []

  for (const [key, schema] of Object.entries(schemas)) {
    if (isEnumSchema(schema)) {
      enums.push(buildEnum(schema["x-enum-name"] ?? toTypeName(key), schema, `#/components/schemas/${key}`))
    }

    if (options.inline) {
      collectInline(schema, toTypeName(key), `#/components/schemas/${key}`, enums)
    }
  }

  return mergeEnums(enums)
}

function collectInline(schema: Schema, prefix: string, origin: string, enums: EnumDefinition[]): void {
  if (!schema || "object" !== typeof schema) {
    return
  }

  for (const member of [...(schema.allOf ?? []), ...(schema.oneOf ?? []), ...(schema.anyOf ?? [])]) {
    collectInline(member, prefix, origin, enums)
  }

  for (const [property, propertySchema] of Object.entries<Schema>(schema.properties ?? {})) {
    const target = isEnumSchema(propertySchema?.items) ? propertySchema.items : propertySchema
    const name = prefix + toTypeName(property)
    const propertyOrigin = `${origin}/properties/${property}`

    if (isEnumSchema(target)) {
      enums.push(buildEnum(target["x-enum-name"] ?? name, target, propertyOrigin))
    } else {
      collectInline(propertySchema, name, propertyOrigin, enums)
    }
  }
}

function isEnumSchema(schema: unknown): schema is Schema {
  return (
    !!schema &&
    "object" === typeof schema &&
    !("$ref" in schema) &&
    Array.isArray((schema as Schema).enum) &&
    (schema as Schema).enum.some((value: unknown) => null !== value)
  )
}

export function buildEnum(name: string, schema: Schema, origin: string): EnumDefinition {
  const declaredKeys: unknown = schema["x-enum-varnames"] ?? schema["x-enumNames"]
  const values: EnumValue[] = []
  const keys: string[] = []

  ;(schema.enum as unknown[]).forEach((value, index) => {
    if (null === value || "object" === typeof value) {
      return
    }

    const declared = Array.isArray(declaredKeys) ? declaredKeys[index] : undefined
    values.push(value as EnumValue)
    keys.push("string" === typeof declared && "" !== declared ? declared : keyFromValue(value as EnumValue))
  })

  const duplicate = keys.find((key, index) => keys.indexOf(key) !== index)

  if (duplicate) {
    throw new Error(`${origin}: key "${duplicate}" appears twice. Declare x-enum-varnames.`)
  }

  const enumDefinition: EnumDefinition = { name: toTypeName(name), values, keys, origin }
  const iris = schema["x-enum-iris"]

  if (iris && "object" === typeof iris) {
    enumDefinition.iris = Object.fromEntries(
      values.flatMap((value, index) => (String(value) in iris ? [[keys[index], iris[String(value)]]] : [])),
    )
  }

  return enumDefinition
}

function keyFromValue(value: EnumValue): string {
  if ("string" === typeof value) {
    return value
  }

  return "VALUE_" + String(value).replace(/^-/, "MINUS_").replace(/\./g, "_")
}

/** `animal.jsonld-read` → `AnimalJsonldRead`: a valid TypeScript identifier. */
export function toTypeName(key: string): string {
  const name = key
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("")

  return /^[0-9]/.test(name) ? `_${name}` : name || "_"
}

/**
 * Merges enums sharing a name. Same values: keep one, joining their IRIs.
 * Different values: refuse rather than silently drop one.
 */
export function mergeEnums(enums: EnumDefinition[]): EnumDefinition[] {
  const byName = new Map<string, EnumDefinition>()

  for (const current of enums) {
    const existing = byName.get(current.name)

    if (!existing) {
      byName.set(current.name, { ...current })
      continue
    }

    if (JSON.stringify(existing.values) !== JSON.stringify(current.values)) {
      throw new Error(
        `Two enums named "${current.name}" with different values: ${existing.origin} and ${current.origin}. ` +
          "Rename one of them with x-enum-name.",
      )
    }

    if (current.iris) {
      existing.iris = { ...existing.iris, ...current.iris }
    }
  }

  return [...byName.values()].sort((a, b) => a.name.localeCompare(b.name))
}

export function renderEnum(enumDefinition: EnumDefinition, options: { asConst?: boolean } = {}): string {
  const { name, values, keys, iris } = enumDefinition
  const asConst = false === options.asConst ? "" : " as const"
  const entries = (map: (key: string, index: number) => unknown) =>
    keys.map((key, index) => `  ${propertyKey(key)}: ${JSON.stringify(map(key, index))},`).join("\n")

  const blocks = [
    `// ${GENERATED_MARKER} — do not edit.`,
    `export const ${name} = ${JSON.stringify(values)}${asConst}`,
    `export const ${name}Enum = {\n${entries((_, index) => values[index])}\n}${asConst}`,
  ]

  if (iris && Object.keys(iris).length > 0) {
    const withIri = keys.filter((key) => key in iris)
    blocks.push(
      `export const ${name}ApiEnum = {\n${withIri
        .map((key) => `  ${propertyKey(key)}: ${JSON.stringify(iris[key])},`)
        .join("\n")}\n}${asConst}`,
    )
  }

  blocks.push(`export type ${name}Values = keyof typeof ${name}Enum`)

  return blocks.join("\n\n") + "\n"
}

function propertyKey(key: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : JSON.stringify(key)
}
