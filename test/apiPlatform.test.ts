import http from "node:http"
import type { AddressInfo } from "node:net"
import path from "node:path"
import { afterAll, beforeAll, describe, expect, it } from "vitest"
import { generate } from "../src/index.js"
import { fixtures } from "./helpers.js"

const config = {
  source: "api-platform.json",
  outDir: "out",
  preset: "api-platform" as const,
  strip: { contentTypes: ["text/csv"] },
  types: false as const,
}

describe("api-platform preset (JSON-LD)", () => {
  it("strips the CSV format schemas along with its content type", async () => {
    const { files } = await generate(config, fixtures)
    const document = JSON.parse(files[0].contents)

    expect(Object.keys(document.components.schemas).sort()).toEqual(["Animal.jsonld", "GenderEnum"])
    expect(document.paths["/api/exports"].get.responses["200"].content).toBeUndefined()
  })

  it("the openapi preset strips only the content type, not the schemas", async () => {
    const { files } = await generate({ ...config, preset: "openapi" }, fixtures)

    expect(Object.keys(JSON.parse(files[0].contents).components.schemas)).toContain("Animal.csv")
  })

  it("rejects a document whose cleanup broke references", async () => {
    const preset = {
      name: "overzealous",
      transform: (document: Record<string, any>) => {
        delete document.components.schemas["Animal.jsonld"]
      },
    }

    await expect(generate({ ...config, preset }, fixtures)).rejects.toThrow(
      "Broken references after cleanup: #/components/schemas/Animal.jsonld.",
    )
  })

  it("emits XxxApiEnum from x-enum-iris, named after x-enum-name", async () => {
    const { files } = await generate(config, fixtures)
    const gender = files.find((file) => file.path.endsWith(`${path.sep}Gender.ts`))!.contents

    expect(gender).toContain(`export const GenderApiEnum = {
  MALE: "/api/genders/MALE",
  FEMALE: "/api/genders/FEMALE",
} as const`)
  })

  describe("Hydra collections fetched over HTTP", () => {
    let server: http.Server
    let host: string

    beforeAll(async () => {
      server = http.createServer((request, response) => {
        const collections: Record<string, unknown> = {
          "/api/public/roles": {
            "@context": "/api/contexts/Role",
            "@type": "Collection",
            member: [
              { "@id": "/api/public/roles/ROLE_USER", "@type": "Role", value: "ROLE_USER" },
              { "@id": "/api/public/roles/ROLE_ADMIN", "@type": "Role", value: "ROLE_ADMIN" },
            ],
          },
          "/api/public/genders": {
            "@context": "/api/contexts/Gender",
            "hydra:member": [
              { "@id": "/api/genders/MALE", value: "MALE" },
              { "@id": "/api/genders/FEMALE", value: "FEMALE" },
            ],
          },
        }
        const body = collections[request.url ?? ""]
        response.writeHead(body ? 200 : 404, { "content-type": "application/ld+json" })
        response.end(JSON.stringify(body ?? {}))
      })
      await new Promise<void>((resolve) => server.listen(0, "127.0.0.1", resolve))
      host = `http://127.0.0.1:${(server.address() as AddressInfo).port}`
    })

    afterAll(() => new Promise<void>((resolve) => server.close(() => resolve())))

    it("generates one enum per collection, merged with the document's", async () => {
      const { files } = await generate(
        { ...config, apiPlatform: { collections: { host, paths: ["/api/public/roles", "/api/public/genders"] } } },
        fixtures,
      )
      const names = files.map((file) => path.basename(file.path)).sort()

      expect(names).toEqual(["Gender.ts", "Role.ts", "openapi.json"])
      expect(files.find((file) => file.path.endsWith("Role.ts"))!.contents).toBe(
        `// Generated by api-dumper — do not edit.

export const Role = ["ROLE_USER","ROLE_ADMIN"] as const

export const RoleEnum = {
  ROLE_USER: "ROLE_USER",
  ROLE_ADMIN: "ROLE_ADMIN",
} as const

export const RoleApiEnum = {
  ROLE_USER: "/api/public/roles/ROLE_USER",
  ROLE_ADMIN: "/api/public/roles/ROLE_ADMIN",
} as const

export type RoleValues = keyof typeof RoleEnum
`,
      )
    })

    it("fails loudly when a collection does not respond", async () => {
      await expect(
        generate({ ...config, apiPlatform: { collections: { host, paths: ["/api/public/missing"] } } }, fixtures),
      ).rejects.toThrow(/404/)
    })

    it("requires a host when the source is a file", async () => {
      await expect(
        generate({ ...config, apiPlatform: { collections: { paths: ["/api/public/roles"] } } }, fixtures),
      ).rejects.toThrow(/host is required/)
    })
  })
})
