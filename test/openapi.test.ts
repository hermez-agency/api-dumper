import fs from "node:fs/promises"
import path from "node:path"
import { describe, expect, it } from "vitest"
import { generate, run } from "../src/index.js"
import { fixtures, read, tempDir } from "./helpers.js"

describe("openapi preset (plain API, YAML)", () => {
  it("generates the types and one file per named enum", async () => {
    const outDir = await tempDir()
    const { changed } = await run({ source: "petstore.yaml", outDir }, { cwd: fixtures })

    expect(changed.map((file) => path.relative(outDir, file)).sort()).toEqual([
      "api-schema.ts",
      "enums/PetStatus.ts",
      "enums/Priority.ts",
      "openapi.json",
    ])

    const types = await read(path.join(outDir, "api-schema.ts"))
    expect(types).toContain("This file was auto-generated by openapi-typescript.")
    expect(types).toContain('"/pets"')

    expect(await read(path.join(outDir, "enums/PetStatus.ts"))).toBe(
      `// Generated by api-dumper — do not edit.

export const PetStatus = ["available","pending","sold"] as const

export const PetStatusEnum = {
  available: "available",
  pending: "pending",
  sold: "sold",
} as const

export type PetStatusValues = keyof typeof PetStatusEnum
`,
    )
  })

  it("takes numeric enum keys from x-enum-varnames", async () => {
    const { files } = await generate({ source: "petstore.yaml", outDir: "out", types: false }, fixtures)
    const priority = files.find((file) => file.path.endsWith("Priority.ts"))!.contents

    expect(priority).toContain("export const Priority = [1,2,3] as const")
    expect(priority).toContain("  LOW: 1,\n  MEDIUM: 2,\n  HIGH: 3,")
  })

  it("names inline enums <Schema><Property> with inline", async () => {
    const { files } = await generate(
      { source: "petstore.yaml", outDir: "out", types: false, enums: { inline: true } },
      fixtures,
    )

    expect(files.map((file) => path.basename(file.path)).sort()).toEqual([
      "PetSize.ts",
      "PetStatus.ts",
      "PetTags.ts",
      "Priority.ts",
      "openapi.json",
    ])
  })

  it("strips content types and paths", async () => {
    const { files } = await generate(
      {
        source: "petstore.yaml",
        outDir: "out",
        types: false,
        enums: false,
        strip: { contentTypes: ["text/csv"], paths: [/^\/internal\//] },
      },
      fixtures,
    )
    const document = JSON.parse(files[0].contents)

    expect(Object.keys(document.paths)).toEqual(["/pets"])
    expect(Object.keys(document.paths["/pets"].get.responses["200"].content)).toEqual(["application/json"])
  })

  it("omits as const when asConst is false", async () => {
    const { files } = await generate(
      { source: "petstore.yaml", outDir: "out", types: false, enums: { asConst: false } },
      fixtures,
    )

    expect(files.find((file) => file.path.endsWith("PetStatus.ts"))!.contents).not.toContain("as const")
  })

  it("--check reports what is out of date, then nothing once written", async () => {
    const outDir = await tempDir()
    const config = { source: "petstore.yaml", outDir }

    expect((await run(config, { cwd: fixtures, check: true })).changed).toHaveLength(4)
    await expect(fs.access(path.join(outDir, "openapi.json"))).rejects.toThrow()

    await run(config, { cwd: fixtures })
    expect(await run(config, { cwd: fixtures, check: true })).toEqual({ changed: [], removed: [] })
  })

  it("removes stale generated enums, never a hand-written file", async () => {
    const outDir = await tempDir()
    const enumDir = path.join(outDir, "enums")
    await fs.mkdir(enumDir, { recursive: true })
    await fs.writeFile(path.join(enumDir, "Old.ts"), "// Generated by api-dumper — do not edit.\n")
    await fs.writeFile(path.join(enumDir, "Legacy.ts"), "\n// ===================== //\n//  Generated - DO NOT EDIT\n")
    await fs.writeFile(path.join(enumDir, "Mine.ts"), "export const mine = 1\n")

    const { removed } = await run({ source: "petstore.yaml", outDir }, { cwd: fixtures })

    expect(removed.map((file) => path.basename(file))).toEqual(["Legacy.ts", "Old.ts"])
    expect((await fs.readdir(enumDir)).sort()).toEqual(["Mine.ts", "PetStatus.ts", "Priority.ts"])
  })

  it("rejects Swagger 2", async () => {
    const dir = await tempDir()
    await fs.writeFile(path.join(dir, "swagger.json"), JSON.stringify({ swagger: "2.0", paths: {} }))

    await expect(generate({ source: "swagger.json", outDir: "out" }, dir)).rejects.toThrow(/Swagger 2/)
  })

  it("rejects two same-named enums with different values", async () => {
    const dir = await tempDir()
    await fs.writeFile(
      path.join(dir, "doc.json"),
      JSON.stringify({
        openapi: "3.0.3",
        info: { title: "t", version: "1" },
        paths: {},
        components: {
          schemas: {
            "Status": { type: "string", enum: ["a"] },
            "status": { type: "string", enum: ["b"] },
          },
        },
      }),
    )

    await expect(generate({ source: "doc.json", outDir: "out", types: false }, dir)).rejects.toThrow(/x-enum-name/)
  })
})
